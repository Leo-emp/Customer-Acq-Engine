// ── Invoice PDF generation with jspdf ──

import { jsPDF } from "jspdf";
import type { Invoice } from "./types";

export function generateInvoicePDF(invoice: Invoice): string {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();

  // ── header ──
  doc.setFontSize(28);
  doc.setTextColor(99, 102, 241); // indigo-500
  doc.text("INVOICE", 20, 30);

  doc.setFontSize(10);
  doc.setTextColor(107, 114, 128); // gray-500
  doc.text(`Invoice #: ${invoice.id}`, 20, 40);
  doc.text(`Date: ${new Date(invoice.createdAt).toLocaleDateString()}`, 20, 46);

  // ── from (right side) ──
  doc.setFontSize(12);
  doc.setTextColor(31, 41, 55); // gray-800
  doc.text("AcquireAI", pageWidth - 20, 30, { align: "right" });
  doc.setFontSize(9);
  doc.setTextColor(107, 114, 128);
  doc.text("AI-Powered Customer Acquisition", pageWidth - 20, 36, { align: "right" });

  // ── bill to ──
  doc.setFontSize(10);
  doc.setTextColor(107, 114, 128);
  doc.text("BILL TO", 20, 65);
  doc.setFontSize(12);
  doc.setTextColor(31, 41, 55);
  doc.text(invoice.companyName, 20, 73);
  doc.setFontSize(10);
  doc.text(invoice.contactName, 20, 80);

  // ── table header ──
  const tableTop = 100;
  doc.setFillColor(249, 250, 251); // gray-50
  doc.rect(20, tableTop - 6, pageWidth - 40, 10, "F");
  doc.setFontSize(9);
  doc.setTextColor(107, 114, 128);
  doc.text("Description", 25, tableTop);
  doc.text("Qty", 120, tableTop, { align: "center" });
  doc.text("Unit Price", 150, tableTop, { align: "center" });
  doc.text("Total", pageWidth - 25, tableTop, { align: "right" });

  // ── table rows ──
  doc.setTextColor(31, 41, 55);
  doc.setFontSize(10);
  let y = tableTop + 12;
  for (const item of invoice.items) {
    doc.text(item.description, 25, y);
    doc.text(String(item.quantity), 120, y, { align: "center" });
    doc.text(`$${item.unitPrice.toFixed(2)}`, 150, y, { align: "center" });
    doc.text(`$${(item.quantity * item.unitPrice).toFixed(2)}`, pageWidth - 25, y, { align: "right" });
    y += 10;
  }

  // ── divider ──
  doc.setDrawColor(229, 231, 235); // gray-200
  doc.line(20, y + 2, pageWidth - 20, y + 2);

  // ── total ──
  y += 14;
  doc.setFontSize(12);
  doc.setTextColor(99, 102, 241);
  doc.text("Total:", 140, y);
  doc.setFontSize(14);
  doc.text(`$${invoice.total.toFixed(2)}`, pageWidth - 25, y, { align: "right" });

  // ── footer ──
  doc.setFontSize(8);
  doc.setTextColor(156, 163, 175); // gray-400
  doc.text("Payment due within 30 days. Thank you for your business.", 20, 270);
  doc.text("Generated by AcquireAI", pageWidth - 20, 270, { align: "right" });

  // return as base64 data URL
  return doc.output("datauristring");
}

export function generateCallNotePDF(
  prospectName: string,
  companyName: string,
  outcome: string,
  summary: string,
  nextAction: string,
  transcript: string,
  insights: string[] = []
): string {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();
  const maxWidth = pageWidth - 40;

  doc.setFontSize(24);
  doc.setTextColor(16, 185, 129);
  doc.text("CALL NOTES", 20, 28);

  doc.setFontSize(10);
  doc.setTextColor(107, 114, 128);
  doc.text(`Date: ${new Date().toLocaleDateString()}`, 20, 38);
  doc.text(`Time: ${new Date().toLocaleTimeString()}`, 20, 44);

  doc.setFontSize(12);
  doc.setTextColor(31, 41, 55);
  doc.text("AcquireAI", pageWidth - 20, 28, { align: "right" });
  doc.setFontSize(9);
  doc.setTextColor(107, 114, 128);
  doc.text("AI Sales Intelligence", pageWidth - 20, 34, { align: "right" });

  let y = 58;

  doc.setFontSize(10);
  doc.setTextColor(107, 114, 128);
  doc.text("PROSPECT", 20, y);
  y += 8;
  doc.setFontSize(12);
  doc.setTextColor(31, 41, 55);
  doc.text(`${prospectName} — ${companyName}`, 20, y);
  y += 12;

  doc.setFontSize(10);
  doc.setTextColor(107, 114, 128);
  doc.text("OUTCOME", 20, y);
  y += 8;
  doc.setFontSize(14);
  const outcomeColor: Record<string, [number, number, number]> = {
    closed: [16, 185, 129], interested: [59, 130, 246], objection: [245, 158, 11], rejected: [239, 68, 68],
  };
  const [r, g, b] = outcomeColor[outcome] || [107, 114, 128];
  doc.setTextColor(r, g, b);
  doc.text(outcome.toUpperCase(), 20, y);
  y += 12;

  doc.setFontSize(10);
  doc.setTextColor(107, 114, 128);
  doc.text("SUMMARY", 20, y);
  y += 8;
  doc.setFontSize(10);
  doc.setTextColor(31, 41, 55);
  const summaryLines = doc.splitTextToSize(summary, maxWidth);
  doc.text(summaryLines, 20, y);
  y += summaryLines.length * 5 + 8;

  doc.setTextColor(107, 114, 128);
  doc.text("NEXT ACTION", 20, y);
  y += 8;
  doc.setTextColor(31, 41, 55);
  const nextLines = doc.splitTextToSize(nextAction, maxWidth);
  doc.text(nextLines, 20, y);
  y += nextLines.length * 5 + 8;

  if (insights.length > 0) {
    doc.setTextColor(107, 114, 128);
    doc.text("KEY INSIGHTS", 20, y);
    y += 8;
    doc.setTextColor(31, 41, 55);
    doc.setFontSize(9);
    for (const insight of insights) {
      if (y > 260) { doc.addPage(); y = 20; }
      const lines = doc.splitTextToSize(`• ${insight}`, maxWidth);
      doc.text(lines, 20, y);
      y += lines.length * 5 + 3;
    }
    y += 5;
  }

  if (transcript) {
    if (y > 220) { doc.addPage(); y = 20; }
    doc.setFontSize(10);
    doc.setTextColor(107, 114, 128);
    doc.text("TRANSCRIPT", 20, y);
    y += 8;

    doc.setDrawColor(229, 231, 235);
    doc.line(20, y - 2, pageWidth - 20, y - 2);

    doc.setFontSize(9);
    doc.setTextColor(55, 65, 81);
    const tLines = doc.splitTextToSize(transcript, maxWidth);
    for (const line of tLines) {
      if (y > 275) { doc.addPage(); y = 20; }
      doc.text(line, 20, y);
      y += 5;
    }
  }

  doc.setFontSize(8);
  doc.setTextColor(156, 163, 175);
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.text("Generated by AcquireAI — AI Sales Intelligence", 20, 287);
    doc.text(`Page ${i} of ${pageCount}`, pageWidth - 20, 287, { align: "right" });
  }

  return doc.output("datauristring");
}
