import { jsPDF } from "jspdf";
import type { Invoice } from "./types";

const BRAND = { indigo: [79, 70, 229] as const, indigoLight: [129, 120, 255] as const, dark: [15, 23, 42] as const, gray800: [31, 41, 55] as const, gray500: [107, 114, 128] as const, gray300: [209, 213, 219] as const, gray100: [243, 244, 246] as const, white: [255, 255, 255] as const, emerald: [16, 185, 129] as const, blue: [59, 130, 246] as const, amber: [245, 158, 11] as const, rose: [239, 68, 68] as const };

function drawRoundedRect(doc: jsPDF, x: number, y: number, w: number, h: number, r: number, style: "F" | "S" | "FD" = "F") {
  doc.roundedRect(x, y, w, h, r, r, style);
}

function drawHeader(doc: jsPDF, pw: number, title: string, color: readonly [number, number, number]) {
  doc.setFillColor(...BRAND.dark);
  doc.rect(0, 0, pw, 52, "F");

  doc.setFillColor(...color);
  doc.rect(0, 48, pw, 4, "F");

  doc.setFontSize(26);
  doc.setTextColor(...BRAND.white);
  doc.text(title, 24, 28);

  doc.setFontSize(10);
  doc.setTextColor(148, 163, 184);
  doc.text("AcquireAI", pw - 24, 22, { align: "right" });
  doc.setFontSize(8);
  doc.text("AI-Powered Customer Acquisition", pw - 24, 30, { align: "right" });

  doc.setFillColor(...color);
  drawRoundedRect(doc, pw - 24 - 60, 34, 60, 12, 3, "F");
  doc.setFontSize(8);
  doc.setTextColor(...BRAND.white);
  doc.text("POWERED BY AI", pw - 24 - 30, 42, { align: "center" });
}

function drawSectionLabel(doc: jsPDF, label: string, x: number, y: number, color: readonly [number, number, number] = BRAND.indigo) {
  doc.setFillColor(...color);
  drawRoundedRect(doc, x, y - 4.5, 3, 6, 1, "F");
  doc.setFontSize(8);
  doc.setTextColor(...BRAND.gray500);
  doc.text(label.toUpperCase(), x + 7, y);
}

function drawFooter(doc: jsPDF, pw: number) {
  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setDrawColor(...BRAND.gray300);
    doc.line(24, 278, pw - 24, 278);
    doc.setFontSize(7);
    doc.setTextColor(...BRAND.gray500);
    doc.text("Generated by AcquireAI — ai-powered customer acquisition engine", 24, 284);
    doc.text(`Page ${i} of ${pages}`, pw - 24, 284, { align: "right" });
  }
}

export function generateInvoicePDF(invoice: Invoice): string {
  const doc = new jsPDF();
  const pw = doc.internal.pageSize.getWidth();
  const contentW = pw - 48;

  drawHeader(doc, pw, "INVOICE", BRAND.indigo);

  let y = 68;

  // invoice meta — two columns
  doc.setFillColor(...BRAND.gray100);
  drawRoundedRect(doc, 24, y, contentW / 2 - 4, 32, 4, "F");
  drawRoundedRect(doc, 24 + contentW / 2 + 4, y, contentW / 2 - 4, 32, 4, "F");

  doc.setFontSize(8);
  doc.setTextColor(...BRAND.gray500);
  doc.text("INVOICE NUMBER", 30, y + 10);
  doc.text("DATE ISSUED", 30 + contentW / 2 + 4, y + 10);
  doc.setFontSize(12);
  doc.setTextColor(...BRAND.gray800);
  doc.text(invoice.id, 30, y + 22);
  doc.text(new Date(invoice.createdAt).toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" }), 30 + contentW / 2 + 4, y + 22);

  y += 44;

  // bill to
  drawSectionLabel(doc, "Bill To", 24, y);
  y += 8;
  doc.setFontSize(14);
  doc.setTextColor(...BRAND.gray800);
  doc.text(invoice.companyName, 24, y);
  y += 7;
  doc.setFontSize(10);
  doc.setTextColor(...BRAND.gray500);
  doc.text(invoice.contactName, 24, y);
  y += 16;

  // table
  doc.setFillColor(...BRAND.dark);
  drawRoundedRect(doc, 24, y, contentW, 11, 3, "F");
  doc.setFontSize(8);
  doc.setTextColor(...BRAND.white);
  doc.text("DESCRIPTION", 30, y + 7.5);
  doc.text("QTY", 115, y + 7.5, { align: "center" });
  doc.text("UNIT PRICE", 145, y + 7.5, { align: "center" });
  doc.text("AMOUNT", pw - 30, y + 7.5, { align: "right" });
  y += 16;

  doc.setFontSize(10);
  for (let i = 0; i < invoice.items.length; i++) {
    const item = invoice.items[i];
    if (i % 2 === 0) {
      doc.setFillColor(...BRAND.gray100);
      drawRoundedRect(doc, 24, y - 5, contentW, 12, 2, "F");
    }
    doc.setTextColor(...BRAND.gray800);
    doc.text(item.description, 30, y + 1);
    doc.setTextColor(...BRAND.gray500);
    doc.text(String(item.quantity), 115, y + 1, { align: "center" });
    doc.text(`$${item.unitPrice.toLocaleString("en-US", { minimumFractionDigits: 2 })}`, 145, y + 1, { align: "center" });
    doc.setTextColor(...BRAND.gray800);
    doc.text(`$${(item.quantity * item.unitPrice).toLocaleString("en-US", { minimumFractionDigits: 2 })}`, pw - 30, y + 1, { align: "right" });
    y += 12;
  }

  y += 4;
  doc.setDrawColor(...BRAND.gray300);
  doc.line(pw / 2, y, pw - 24, y);

  // subtotal + total
  y += 10;
  doc.setFontSize(10);
  doc.setTextColor(...BRAND.gray500);
  doc.text("Subtotal", pw - 80, y);
  doc.setTextColor(...BRAND.gray800);
  doc.text(`$${invoice.total.toLocaleString("en-US", { minimumFractionDigits: 2 })}`, pw - 30, y, { align: "right" });

  y += 8;
  doc.setTextColor(...BRAND.gray500);
  doc.text("Tax (0%)", pw - 80, y);
  doc.text("$0.00", pw - 30, y, { align: "right" });

  y += 12;
  doc.setFillColor(...BRAND.indigo);
  drawRoundedRect(doc, pw / 2, y - 6, pw / 2 - 24, 16, 4, "F");
  doc.setFontSize(12);
  doc.setTextColor(...BRAND.white);
  doc.text("TOTAL DUE", pw - 80, y + 4);
  doc.setFontSize(16);
  doc.text(`$${invoice.total.toLocaleString("en-US", { minimumFractionDigits: 2 })}`, pw - 30, y + 4, { align: "right" });

  // payment terms
  y += 28;
  doc.setFillColor(249, 250, 251);
  drawRoundedRect(doc, 24, y, contentW, 22, 4, "F");
  doc.setFontSize(8);
  doc.setTextColor(...BRAND.gray500);
  doc.text("PAYMENT TERMS", 30, y + 8);
  doc.setFontSize(9);
  doc.setTextColor(...BRAND.gray800);
  doc.text("Net 30 — Payment due within 30 days of invoice date. Thank you for your business.", 30, y + 16);

  drawFooter(doc, pw);
  return doc.output("datauristring");
}

export function generateCallNotePDF(
  prospectName: string,
  companyName: string,
  outcome: string,
  summary: string,
  nextAction: string,
  transcript: string,
  insights: string[] = []
): string {
  const doc = new jsPDF();
  const pw = doc.internal.pageSize.getWidth();
  const maxW = pw - 48;

  const outcomeColors: Record<string, readonly [number, number, number]> = {
    closed: BRAND.emerald, interested: BRAND.blue, objection: BRAND.amber, rejected: BRAND.rose,
  };
  const accentColor = outcomeColors[outcome] || BRAND.gray500;

  drawHeader(doc, pw, "CALL NOTES", accentColor);

  let y = 68;

  // info cards row
  const cardW = (maxW - 8) / 3;
  const cards = [
    { label: "PROSPECT", value: prospectName },
    { label: "COMPANY", value: companyName },
    { label: "DATE & TIME", value: `${new Date().toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric" })} ${new Date().toLocaleTimeString("en-US", { hour: "2-digit", minute: "2-digit" })}` },
  ];
  cards.forEach((card, i) => {
    const cx = 24 + i * (cardW + 4);
    doc.setFillColor(...BRAND.gray100);
    drawRoundedRect(doc, cx, y, cardW, 28, 4, "F");
    doc.setFontSize(7);
    doc.setTextColor(...BRAND.gray500);
    doc.text(card.label, cx + 6, y + 10);
    doc.setFontSize(11);
    doc.setTextColor(...BRAND.gray800);
    const truncated = card.value.length > 20 ? card.value.slice(0, 18) + "..." : card.value;
    doc.text(truncated, cx + 6, y + 20);
  });
  y += 38;

  // outcome badge
  drawSectionLabel(doc, "Outcome", 24, y, accentColor);
  y += 6;
  doc.setFillColor(...accentColor);
  drawRoundedRect(doc, 24, y, 60, 14, 4, "F");
  doc.setFontSize(12);
  doc.setTextColor(...BRAND.white);
  doc.text(outcome.toUpperCase(), 54, y + 9.5, { align: "center" });
  y += 24;

  // summary
  drawSectionLabel(doc, "Summary", 24, y);
  y += 6;
  doc.setFontSize(10);
  doc.setTextColor(...BRAND.gray800);
  const sLines = doc.splitTextToSize(summary, maxW);
  doc.text(sLines, 24, y);
  y += sLines.length * 5 + 10;

  // next action
  drawSectionLabel(doc, "Recommended Next Action", 24, y, BRAND.emerald);
  y += 6;
  doc.setFillColor(236, 253, 245);
  const naLines = doc.splitTextToSize(nextAction, maxW - 16);
  drawRoundedRect(doc, 24, y - 4, maxW, naLines.length * 5 + 12, 4, "F");
  doc.setFontSize(10);
  doc.setTextColor(6, 95, 70);
  doc.text(naLines, 32, y + 4);
  y += naLines.length * 5 + 16;

  // insights
  if (insights.length > 0) {
    if (y > 220) { doc.addPage(); y = 20; }
    drawSectionLabel(doc, "Key Insights", 24, y, BRAND.blue);
    y += 8;
    doc.setFontSize(9);
    for (const insight of insights) {
      if (y > 265) { doc.addPage(); y = 20; }
      doc.setFillColor(...BRAND.blue);
      doc.circle(28, y - 1, 1.5, "F");
      doc.setTextColor(...BRAND.gray800);
      const iLines = doc.splitTextToSize(insight, maxW - 12);
      doc.text(iLines, 34, y);
      y += iLines.length * 5 + 4;
    }
    y += 6;
  }

  // transcript
  if (transcript) {
    if (y > 200) { doc.addPage(); y = 20; }
    drawSectionLabel(doc, "Full Transcript", 24, y);
    y += 8;

    doc.setFillColor(248, 250, 252);
    const tLines = doc.splitTextToSize(transcript, maxW - 16);
    const blockH = Math.min(tLines.length * 4.5 + 12, 200);
    drawRoundedRect(doc, 24, y - 4, maxW, blockH, 4, "F");

    doc.setDrawColor(...BRAND.gray300);
    doc.line(28, y - 4, 28, y - 4 + blockH);

    doc.setFontSize(8);
    doc.setTextColor(71, 85, 105);
    for (const line of tLines) {
      if (y > 272) { doc.addPage(); y = 20; doc.setFillColor(248, 250, 252); doc.setTextColor(71, 85, 105); }
      doc.text(line, 34, y);
      y += 4.5;
    }
  }

  drawFooter(doc, pw);
  return doc.output("datauristring");
}

// ── Competitor Analysis PDF ──
export function generateCompetitorPDF(data: {
  competitors: { name: string; description: string; strengths: string[]; weaknesses: string[]; pricing: string; marketPosition: string; threatLevel: string }[];
  ourAdvantages?: string[];
  strategicRecommendations?: string[];
}, companyName: string): string {
  const doc = new jsPDF();
  const pw = doc.internal.pageSize.getWidth();
  const maxW = pw - 48;
  drawHeader(doc, pw, "COMPETITIVE ANALYSIS", BRAND.rose);
  let y = 64;
  doc.setFontSize(10); doc.setTextColor(...BRAND.gray500);
  doc.text(`Prepared for ${companyName} — ${new Date().toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric" })}`, 24, y);
  y += 14;

  for (const comp of data.competitors) {
    if (y > 230) { doc.addPage(); y = 20; }
    const threatColors: Record<string, readonly [number, number, number]> = { high: BRAND.rose, medium: BRAND.amber, low: BRAND.emerald };
    const tc = threatColors[comp.threatLevel] || BRAND.gray500;
    doc.setFillColor(...BRAND.gray100);
    drawRoundedRect(doc, 24, y - 4, maxW, 10, 3, "F");
    doc.setFontSize(12); doc.setTextColor(...BRAND.gray800); doc.text(comp.name, 30, y + 2);
    doc.setFillColor(...tc);
    drawRoundedRect(doc, pw - 70, y - 2, 40, 8, 2, "F");
    doc.setFontSize(7); doc.setTextColor(...BRAND.white);
    doc.text(`${comp.threatLevel.toUpperCase()} THREAT`, pw - 50, y + 3, { align: "center" });
    y += 14;
    doc.setFontSize(8); doc.setTextColor(...BRAND.gray500);
    doc.text(`Position: ${comp.marketPosition} | Pricing: ${comp.pricing}`, 30, y); y += 6;
    const descLines = doc.splitTextToSize(comp.description, maxW - 12);
    doc.setTextColor(...BRAND.gray800); doc.text(descLines, 30, y); y += descLines.length * 4 + 4;
    doc.setFontSize(7); doc.setTextColor(...BRAND.emerald); doc.text("STRENGTHS", 30, y); y += 4;
    doc.setFontSize(8); doc.setTextColor(...BRAND.gray800);
    for (const s of comp.strengths.slice(0, 3)) { doc.text(`+ ${s}`, 34, y); y += 4; }
    y += 2;
    doc.setFontSize(7); doc.setTextColor(...BRAND.rose); doc.text("WEAKNESSES", 30, y); y += 4;
    doc.setFontSize(8); doc.setTextColor(...BRAND.gray800);
    for (const w of comp.weaknesses.slice(0, 3)) { doc.text(`- ${w}`, 34, y); y += 4; }
    y += 8;
  }
  if (data.ourAdvantages?.length) {
    if (y > 220) { doc.addPage(); y = 20; }
    drawSectionLabel(doc, "Our Advantages", 24, y, BRAND.emerald); y += 8;
    doc.setFontSize(9);
    for (const a of data.ourAdvantages) {
      if (y > 270) { doc.addPage(); y = 20; }
      doc.setFillColor(...BRAND.emerald); doc.circle(28, y - 1, 1.5, "F");
      doc.setTextColor(...BRAND.gray800);
      const lines = doc.splitTextToSize(a, maxW - 12); doc.text(lines, 34, y); y += lines.length * 4.5 + 4;
    }
  }
  if (data.strategicRecommendations?.length) {
    y += 4; if (y > 220) { doc.addPage(); y = 20; }
    drawSectionLabel(doc, "Strategic Recommendations", 24, y, BRAND.blue); y += 8;
    doc.setFontSize(9);
    for (let i = 0; i < data.strategicRecommendations.length; i++) {
      if (y > 270) { doc.addPage(); y = 20; }
      doc.setTextColor(...BRAND.blue); doc.text(`${i + 1}.`, 28, y);
      doc.setTextColor(...BRAND.gray800);
      const lines = doc.splitTextToSize(data.strategicRecommendations[i], maxW - 16); doc.text(lines, 34, y); y += lines.length * 4.5 + 4;
    }
  }
  drawFooter(doc, pw);
  return doc.output("datauristring");
}

// ── Industry Research PDF ──
export function generateIndustryPDF(data: {
  overview: { industryName: string; marketSize: string; growthRate: string; maturityStage: string; summary: string };
  trends: { trend: string; impact: string; timeframe: string; relevance: string }[];
  keyPlayers: { name: string; role: string; marketShare: string }[];
  opportunities: { opportunity: string; description: string; difficulty: string; potentialRevenue: string }[];
  outlook: string;
}, companyName: string): string {
  const doc = new jsPDF();
  const pw = doc.internal.pageSize.getWidth();
  const maxW = pw - 48;
  drawHeader(doc, pw, "INDUSTRY REPORT", BRAND.blue);
  let y = 64;
  doc.setFontSize(10); doc.setTextColor(...BRAND.gray500);
  doc.text(`${data.overview.industryName} — Prepared for ${companyName}`, 24, y); y += 14;

  const sCardW = (maxW - 8) / 3;
  [
    { label: "MARKET SIZE", value: data.overview.marketSize },
    { label: "GROWTH RATE", value: data.overview.growthRate },
    { label: "MATURITY", value: data.overview.maturityStage.toUpperCase() },
  ].forEach((s, i) => {
    const cx = 24 + i * (sCardW + 4);
    doc.setFillColor(...BRAND.gray100); drawRoundedRect(doc, cx, y, sCardW, 28, 4, "F");
    doc.setFontSize(7); doc.setTextColor(...BRAND.gray500); doc.text(s.label, cx + 6, y + 10);
    doc.setFontSize(14); doc.setTextColor(...BRAND.gray800); doc.text(s.value, cx + 6, y + 22);
  });
  y += 38;
  doc.setFontSize(10); doc.setTextColor(...BRAND.gray800);
  const sumLines = doc.splitTextToSize(data.overview.summary, maxW); doc.text(sumLines, 24, y); y += sumLines.length * 5 + 10;

  drawSectionLabel(doc, "Key Trends", 24, y, BRAND.blue); y += 8;
  for (const t of data.trends) {
    if (y > 250) { doc.addPage(); y = 20; }
    doc.setFontSize(10); doc.setTextColor(...BRAND.gray800); doc.text(t.trend, 30, y);
    const relColor: readonly [number, number, number] = t.relevance === "high" ? BRAND.rose : t.relevance === "medium" ? BRAND.amber : BRAND.emerald;
    doc.setFontSize(7); doc.setTextColor(...relColor);
    doc.text(`${t.relevance.toUpperCase()} · ${t.timeframe}`, pw - 30, y, { align: "right" }); y += 5;
    doc.setFontSize(8); doc.setTextColor(...BRAND.gray500);
    const impLines = doc.splitTextToSize(t.impact, maxW - 12); doc.text(impLines, 30, y); y += impLines.length * 4 + 6;
  }

  if (y > 220) { doc.addPage(); y = 20; }
  drawSectionLabel(doc, "Key Players", 24, y, BRAND.indigo); y += 8;
  doc.setFillColor(...BRAND.dark); drawRoundedRect(doc, 24, y, maxW, 10, 3, "F");
  doc.setFontSize(8); doc.setTextColor(...BRAND.white);
  doc.text("COMPANY", 30, y + 7); doc.text("ROLE", 90, y + 7); doc.text("SHARE", pw - 30, y + 7, { align: "right" }); y += 14;
  for (const p of data.keyPlayers) {
    if (y > 270) { doc.addPage(); y = 20; }
    doc.setFontSize(9); doc.setTextColor(...BRAND.gray800); doc.text(p.name, 30, y);
    doc.setTextColor(...BRAND.gray500); doc.text(p.role.slice(0, 40), 90, y);
    doc.text(p.marketShare, pw - 30, y, { align: "right" }); y += 6;
  }

  y += 8; if (y > 220) { doc.addPage(); y = 20; }
  drawSectionLabel(doc, "Opportunities", 24, y, BRAND.emerald); y += 8;
  for (const o of data.opportunities) {
    if (y > 250) { doc.addPage(); y = 20; }
    doc.setFontSize(10); doc.setTextColor(...BRAND.gray800); doc.text(o.opportunity, 30, y);
    doc.setFontSize(7); doc.setTextColor(...BRAND.emerald);
    doc.text(`${o.potentialRevenue} · ${o.difficulty}`, pw - 30, y, { align: "right" }); y += 5;
    doc.setFontSize(8); doc.setTextColor(...BRAND.gray500);
    const dLines = doc.splitTextToSize(o.description, maxW - 12); doc.text(dLines, 30, y); y += dLines.length * 4 + 6;
  }

  y += 4; if (y > 230) { doc.addPage(); y = 20; }
  drawSectionLabel(doc, "Outlook", 24, y, BRAND.blue); y += 8;
  doc.setFillColor(239, 246, 255);
  const olLines = doc.splitTextToSize(data.outlook, maxW - 16);
  drawRoundedRect(doc, 24, y - 4, maxW, olLines.length * 5 + 12, 4, "F");
  doc.setFontSize(10); doc.setTextColor(30, 64, 175); doc.text(olLines, 32, y + 4);
  drawFooter(doc, pw);
  return doc.output("datauristring");
}

